//! Protobuf messages and gRPC services for Hivekeep.
//!
//! Each proto package is exposed as a module mirroring its package path:
//!
//! | package               | module                 | contents                                   |
//! |-----------------------|------------------------|--------------------------------------------|
//! | `hivekeep.api.v1`     | [`api::v1`]            | public `Control` and `WorkerService` APIs  |
//! | `hivekeep.keeper.v1`  | [`keeper::v1`]         | node agent (`Keeper`, `WorkerSupport`)     |
//! | `hivekeep.worker.v1`  | [`worker::v1`]         | sandbox worker (`Worker`)                  |
//! | `hivekeep.config.v1`  | [`config::v1`]         | `hivekeep-api` configuration file          |
//!
//! Every service has both a client (`<service>_client`) and a server
//! (`<service>_server`) module generated by tonic.

#![allow(
    clippy::doc_lazy_continuation,
    clippy::large_enum_variant,
    clippy::enum_variant_names
)]

/// Public control-plane API.
pub mod api {
    /// Version 1 of the public API.
    pub mod v1 {
        tonic::include_proto!("hivekeep.api.v1");
    }
}

/// Node agent API.
pub mod keeper {
    /// Version 1 of the node agent API.
    pub mod v1 {
        tonic::include_proto!("hivekeep.keeper.v1");
    }
}

/// Sandbox worker API.
pub mod worker {
    /// Version 1 of the sandbox worker API.
    pub mod v1 {
        tonic::include_proto!("hivekeep.worker.v1");
    }
}

/// Configuration file schemas.
pub mod config {
    /// Version 1 of the configuration schema.
    pub mod v1 {
        tonic::include_proto!("hivekeep.config.v1");
    }
}

/// Encoded `FileDescriptorSet` of every Hivekeep proto, for gRPC reflection.
pub const FILE_DESCRIPTOR_SET: &[u8] =
    include_bytes!(concat!(env!("OUT_DIR"), "/hivekeep_descriptor.bin"));

#[cfg(test)]
mod tests {
    use super::*;
    use prost::Message;

    #[test]
    fn renamed_fields_keep_their_wire_numbers() {
        // ObjectRef { hive = 1, name = 2 } must encode exactly as before the rename.
        let r = api::v1::ObjectRef {
            hive: "h".into(),
            name: "n".into(),
        };
        assert_eq!(r.encode_to_vec(), vec![0x0a, 1, b'h', 0x12, 1, b'n']);
    }

    #[test]
    fn descriptor_set_is_embedded() {
        let set = prost_types::FileDescriptorSet::decode(FILE_DESCRIPTOR_SET).unwrap();
        let names: Vec<_> = set.file.iter().filter_map(|f| f.package.clone()).collect();
        for pkg in [
            "hivekeep.api.v1",
            "hivekeep.keeper.v1",
            "hivekeep.worker.v1",
            "hivekeep.config.v1",
        ] {
            assert!(names.iter().any(|n| n == pkg), "missing {pkg}");
        }
    }
}
